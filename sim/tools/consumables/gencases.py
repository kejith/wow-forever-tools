"""Writes cases_test.go next to this file: what scripts/consumables.py makes of the two small DB2 worlds of
scripts/test_consumables.py (the catalog as json.dump writes it), and its answers for float floor division,
uses_in, fight_delta, restore_text and fmt_duration.

    uv run sim/tools/consumables/gencases.py && gofmt -w sim/tools/consumables
"""
import csv
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(HERE, "..", "..", "..", "scripts")
sys.path.insert(0, SCRIPTS)
import consumables as c  # noqa: E402
import i18n  # noqa: E402
import test_consumables as t  # noqa: E402

i18n.set_language("en")


def csv_text(rows: list[dict]) -> str:
    header: list[str] = []
    for r in rows:
        header += [k for k in r if k not in header]
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=header, restval="")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def go(s: str) -> str:
    return json.dumps(s)


worlds = {"page": t.TABLES, "fight": t.FIGHT_TABLES}
catalogs = {}
out = ["// Code generated by a Python script from Python's own output; DO NOT EDIT.", "", "package consumables", ""]
out += ["var worldCases = []struct {", "\tname    string", "\ttables  map[string]string", "\tcatalog string", "}{"]
for name, tables in worlds.items():
    real = c.icons.table
    c.icons.table = lambda n, build, locale=None, tables=tables: tables.get(n, [])
    try:
        cat = c.build_catalog("1.0.0.1", "enUS")
    finally:
        c.icons.table = real
    catalogs[name] = cat
    out.append("\t{" + go(name) + ", map[string]string{")
    for table, rows in tables.items():
        out.append(f"\t\t{go(table)}: {go(csv_text(rows))},")
    out.append("\t}, " + go(json.dumps(cat, ensure_ascii=False)) + "},")
out.append("}")
out.append("")

floats = [(0.0, 120.0), (59.999, 120.0), (119.999, 120.0), (120.0, 120.0), (149.999, 120.0), (-1.0, 120.0),
          (0.3, 0.1), (7.0, -2.0), (-7.0, 2.0), (1e-300, 120.0), (239.999, 120.0)]
out += ["var floorDivCases = []struct{ x, y, want float64 }{"]
for x, y in floats:
    out.append(f"\t{{{x!r}, {y!r}, {x // y!r}}},")
out += ["}", ""]

out += ["var usesCases = []struct {", "\tseconds float64", "\twant    int64", "}{"]
for s in [0.0, 0.5, 1.0, 60.0, 120.0, 120.001, 150.0, 240.0, 240.0005, 600.0]:
    out.append(f"\t{{{s!r}, {c.uses_in(s)}}},")
out += ["}", ""]

out += ["var deltaCases = []struct {", "\tworld, id, kind string", "\tseconds, hps    float64", "\twant            string",
        "}{"]
for name, cat in catalogs.items():
    for iid, it in cat["items"].items():
        kind = c.fight_kind(it) or "other"
        for seconds in (0.5, 30.0, 60.0, 150.0, 600.0):
            for hps in (10.0, 12.0, 0.0):
                d = c.fight_delta(it, kind, seconds, hps)
                out.append(f"\t{{{go(name)}, {go(iid)}, {go(kind)}, {seconds!r}, {hps!r}, {go(json.dumps(d))}}},")
out += ["}", ""]

out += ["var restoreCases = []struct {", "\tworld, id string", "\tindex     int", "\twant      string", "}{"]
for name, cat in catalogs.items():
    for iid, it in cat["items"].items():
        for i, r in enumerate(it["restore"]):
            out.append(f"\t{{{go(name)}, {go(iid)}, {i}, {go(c.restore_text(r))}}},")
out += ["}", ""]

out += ["var durationCases = []struct {", "\tseconds int64", "\twant    any", "}{"]
for s in [0, 1, 30, 59, 60, 89, 90, 150, 3599, 3600, 5400, 7200, 1800]:
    v = c.fmt_duration(s)
    out.append(f"\t{{{s}, {'nil' if v is None else go(v)}}},")
out += ["}", ""]

with open(os.path.join(HERE, "cases_test.go"), "w", encoding="utf-8") as f:
    f.write("\n".join(out))
