"""Writes cases_test.go: made-up BLP2 files of every kind, decoded by Pillow (what scripts/icons.py used).

    uv run sim/tools/icons/gencases.py
"""

import io
import os
import random
import struct

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))


def blp(encoding, alpha_depth, alpha_encoding, w, h, mip, compression=1, magic=b"BLP2"):
    rnd = random.Random(f"{encoding}{alpha_depth}{alpha_encoding}{w}{h}{len(mip)}")
    palette = bytes(rnd.randrange(256) for _ in range(1024))
    head = magic + struct.pack("<iBBBB", compression, encoding, alpha_depth, alpha_encoding, 1) + struct.pack("<II", w, h)
    offsets = [20 + 128 + 1024] + [0] * 15
    lengths = [len(mip)] + [0] * 15
    return head + struct.pack("<16I", *offsets) + struct.pack("<16I", *lengths) + palette + mip


def noise(n, seed):
    rnd = random.Random(seed)
    return bytes(rnd.randrange(256) for _ in range(n))


def dxt_blocks(n, size, seed):
    """n blocks; every other one with color0 <= color1, so both DXT1 modes occur."""
    out = bytearray(noise(n * size, seed))
    for i in range(n):
        at = i * size + (0 if size == 8 else 8)
        c0, c1 = struct.unpack_from("<HH", out, at)
        if i % 2:
            c0, c1 = min(c0, c1), max(c0, c1)
        else:
            c0, c1 = max(c0, c1) | 1, min(c0, c1) & ~1
        struct.pack_into("<HH", out, at, c0, c1)
    return bytes(out)


CASES = [
    ("palette without alpha", blp(1, 0, 0, 8, 4, noise(32, 1))),
    ("palette with 1-bit alpha", blp(1, 1, 0, 8, 4, noise(32 + 4, 2))),
    ("palette with 8-bit alpha", blp(1, 8, 0, 8, 4, noise(32 + 32, 3))),
    ("palette too short", blp(1, 8, 0, 8, 4, noise(20, 4))),
    ("dxt1", blp(2, 0, 0, 8, 8, dxt_blocks(4, 8, 5))),
    ("dxt1 with alpha", blp(2, 1, 0, 8, 8, dxt_blocks(4, 8, 6))),
    ("dxt3", blp(2, 8, 1, 8, 4, dxt_blocks(2, 16, 7))),
    ("dxt5", blp(2, 8, 7, 8, 8, dxt_blocks(4, 16, 8))),
    ("dxt5 without the alpha flag", blp(2, 0, 7, 8, 4, dxt_blocks(2, 16, 9))),
    ("dxt1 of width 6", blp(2, 0, 0, 6, 4, dxt_blocks(2, 8, 10))),
    ("dxt1 cut short", blp(2, 0, 0, 8, 8, dxt_blocks(3, 8, 11))),
    ("unknown alpha encoding", blp(2, 8, 3, 8, 4, dxt_blocks(2, 16, 12))),
    ("raw bgra", blp(3, 8, 0, 4, 4, noise(64, 13))),
    ("jpeg compression", blp(1, 0, 0, 4, 4, noise(16, 14), compression=0)),
    ("not a blp", b"<html>not found</html>" + bytes(2000)),
]


def decode(data):
    try:
        return Image.open(io.BytesIO(data)).convert("RGBA")
    except Exception:
        return None


def main():
    lines = ["// Code generated by gencases.py; DO NOT EDIT.", "", "package icons", "",
             "var pillowCases = []struct {", "\tname, blp string // hex", "\tw, h    int",
             "\trgba    string // hex; \"\" = Pillow cannot decode it", "}{"]
    for name, data in CASES:
        img = decode(data)
        w, h, rgba = (img.width, img.height, img.tobytes().hex()) if img else (0, 0, "")
        lines.append(f'\t{{"{name}", "{data.hex()}", {w}, {h}, "{rgba}"}},')
    lines.append("}")
    with open(os.path.join(HERE, "cases_test.go"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
