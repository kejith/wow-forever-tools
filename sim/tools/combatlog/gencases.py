"""Writes cases_test.go next to this file: what Python's csv module, int(), float(), int(x, 16) and
datetime.date.toordinal() make of the texts a combat log may hold, as scripts/combatlog.py reads them.

    python3 sim/tools/combatlog/gencases.py && gofmt -w sim/tools/combatlog
"""
import csv
import datetime
import json
import os

# Lines as combatlog.read hands them to the csv module: the text after the time stamp, with its ending.
lines = [
    'SPELL_CAST_SUCCESS,Player-1-0001,"Name-Realm",0x511,0x0,0000000000000000,nil,0x80000000,0x80000000,686,'
    '"Shadow Bolt",0x20\r\n',
    'A,"quoted, with comma",B\r\n',
    'A,"a ""quote"" inside",B\n',
    'A,"",,B\r',
    '\r\n',
    'only\r\n',
    'A,"closed"after,B\r\n',
    'A,mid"quote,B\r\n',
    'trailing,\r\n',
    ',leading\r\n',
    'no ending',
    'A,"Grün",ß\r\n',
]
# A quoted field that goes on into the next line: one record from two lines.
multi = ['A,"first\r\n', 'second",B\r\n']

ints = ["16", " 7 ", "+3", "-4", "1_000", "_1", "1__0", "", "x", "08", "1.0", "0x10"]
floats = ["44.216", "1", "-2.5", " 3 ", "1e3", "inf", "-Infinity", "nan", "1_000.5", "nil", "", "0x10", "1e400",
          ".5", "5.", "1,5", "abc"]
hexes = ["0x511", "0x80000000", "511", "0X1F", "-0x10", "zz", "", "nil", "0x_1", "1_0"]
dates = [(2026, 11, 20), (1, 1, 1), (2024, 2, 29), (2026, 2, 29), (2026, 13, 1), (2026, 4, 31), (9999, 12, 31),
         (0, 1, 1)]

out = ["// Code generated by a Python script from Python's own output; DO NOT EDIT.", "", "package combatlog", ""]
out += ["var csvCases = []struct {", "\tlines []string", "\twant  [][]string", "}{"]
for group in [[x] for x in lines] + [multi]:
    rows = list(csv.reader(group))
    out.append("\t{%s, %s}," % ("[]string{" + ", ".join(json.dumps(x) for x in group) + "}",
                                "[][]string{" + ", ".join("{" + ", ".join(json.dumps(f, ensure_ascii=False) for f in r)
                                                          + "}" for r in rows) + "}"))
out.append("}")


def try_(f):
    try:
        return f(), True
    except (ValueError, OverflowError):
        return 0, False


out += ["", "var intCases = []struct {", "\ttext string", "\twant int64", "\tok   bool", "}{"]
for x in ints:
    v, ok = try_(lambda: int(x))
    out.append("\t{%s, %d, %s}," % (json.dumps(x), v, "true" if ok else "false"))
out.append("}")
out += ["", "var floatCases = []struct {", "\ttext string", "\twant float64", "\tok   bool", "}{"]
for x in floats:
    v, ok = try_(lambda: float(x))
    if v != v:
        lit = "math.NaN()"
    elif v in (float("inf"), float("-inf")):
        lit = "math.Inf(%d)" % (1 if v > 0 else -1)
    else:
        lit = json.dumps(v)
    out.append("\t{%s, %s, %s}," % (json.dumps(x), lit, "true" if ok else "false"))
out.append("}")
out += ["", "var flagCases = []struct {", "\ttext string", "\twant int64", "}{"]
for x in hexes:
    v, ok = try_(lambda: int(x, 16))
    out.append("\t{%s, %d}," % (json.dumps(x), v if ok else 0))
out.append("}")
out += ["", "var dateCases = []struct {", "\ty, m, d int64", "\twant    int64", "\tok      bool", "}{"]
for y, m, d in dates:
    v, ok = try_(lambda: datetime.date(y, m, d).toordinal())
    out.append("\t{%d, %d, %d, %d, %s}," % (y, m, d, v, "true" if ok else "false"))
out.append("}")
text = "\n".join(out) + "\n"
if "math." in text:
    text = text.replace('package combatlog\n', 'package combatlog\n\nimport "math"\n', 1)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "cases_test.go"), "w").write(text)
print(len(out), "lines")
