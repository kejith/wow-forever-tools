"""Writes cases_test.go next to this file: what Python's str.lower() makes of item names (the sort key of the
price history) and what scripts/pricehistory.days_of makes of hand-made entries of Auctionator's database.

    uv run --with lupa python sim/tools/pricehistory/gencases.py && gofmt -w sim/tools/pricehistory
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "scripts"))
import pricehistory  # noqa: E402

texts = ["Friedensblume", "ÄPFEL und Öl", "Straße", "STRASSE", "ẞ", "İstanbul", "ΟΔΟΣ", "ΟΔΟΣ ΣΑ", "Σ", "ΑΣ.", "ΑΣ'Β",
         "ǅemal", "ΩK", "Ⅻ", "Ǆ", "ﬀ", "Robe der Tests", "OLDRecruit's Belt", "[PH] Gürtel", "ÉCLAIR", "Ꭰ", "𐐀"]


def lua(v):
    """A Python value as the Lua text whose table sv.Parse reads back as the same dict."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    return "{" + ", ".join("[%s] = %s" % (json.dumps(k), lua(x)) for k, x in v.items()) + "}"


# Entries as the CBOR decoder makes them: string keys, ints, floats, bools; an empty CBOR array is a list.
entries = [
    {"h": {"2512": 35, "2510": 40, "2513": 158}, "l": {"2512": 30, "2513": 999}, "a": {"2510": 50, "2513": 12}},
    {"h": {"10": 2.5, "11": 3.5, "12": 0.5, "13": 1.5}, "l": {"10": 0.5, "11": 0, "12": -1, "13": 1.5}},
    {"h": {"5": True, "6": False, "7": -3, "x": 9, "8": "12", "0012": 4}, "a": {"5": 2.9, "0012": True, "7": 1}},
    {"h": {"20": 100}, "l": [], "a": []},
    {"h": [], "l": {"1": 5}},
    {"h": {"3": 1e3, "4": 7.25}, "l": {"3": 999.5, "4": 7.25}, "a": {"3": -1.5, "4": "9"}},
]

out = ["// Code generated by a Python script from Python's own output; DO NOT EDIT.", "", "package pricehistory", "",
       "var lowerCases = []struct{ text, want string }{"]
for t in texts:
    out.append("\t{%s, %s}," % (json.dumps(t, ensure_ascii=False), json.dumps(t.lower(), ensure_ascii=False)))
out += ["}", "", "var daysCases = []struct{ lua, want string }{"]
for e in entries:
    out.append("\t{%s, %s}," % (json.dumps(lua(e), ensure_ascii=False), json.dumps(json.dumps(pricehistory.days_of(e)))))
out.append("}")
with open(os.path.join(HERE, "cases_test.go"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
