"""Writes cases_test.go next to this file: what scripts/goldperhour.py makes of hand-made GoldPerHourDB tables
(read through lupa as the bridge reads them), with the quirks of Python's `or`, round() and sorted().

    uv run --with lupa python sim/tools/goldperhour/gencases.py && gofmt -w sim/tools/goldperhour
"""
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "scripts"))
import goldperhour  # noqa: E402
import upgrades  # noqa: E402

LINK = "|cff1EFF00|Hitem:2589::::::::20:::::|h[Linen Cloth]|h|r"
# Lua sources of GoldPerHourDB. No ties among values Python takes from a dict: lupa's key order is random.
cases = [
    # Rounding half to even, an ID of 0 and an empty name taken from the link, the quality from its color.
    """GoldPerHourDB = { elapsed = 59, gold = { herb = 2.5, loot = 3.5 }, coin = { herb = 0.5, loot = 1.5 },
      items = { herb = { { id = 0, name = "", link = "%s", count = 2, value = 2.5 } },
                loot = { [9] = { id = 7, value = 3.5 }, [8] = { id = 5, name = "B", value = 4.5, quality = 0 } } } }"""
    % LINK,
    # A minute exactly; ended 0 falls back to lastActive; zones with fractions; characters as a list.
    """GoldPerHourDB = { elapsed = 60.0, gold = { loot = 1000 }, settings = { scale = 1.5, foo = 1,
      priceSource = "vendor", autoStart = false }, hidden = false, herbSpells = { [12] = true, [3] = false,
      ["7"] = true, [5] = true },
      session = { started = 100, ended = 0, lastActive = 250, zones = { A = 10.5, B = 99.5, C = 0.5 },
                  chars = { true, false, true }, samples = { { 0, 1, 2 }, { 1, 2 }, 5, { 3, 4, 5, 6 } } } }""",
    # History: sorted by start (or archive time) newest first, the best per hour, sessions without one.
    """GoldPerHourDB = { version = "0.3.1", updated = 5, resume = 1, settings = {}, lastRequest = { id = 3 },
      history = {
        { started = 10, elapsed = 3600, gold = { herb = 100, loot = 50 }, chars = { Zed = true, Amy = true } },
        { archived = 30, elapsed = 30, gold = { loot = 99 } },
        { started = 20, elapsed = 120.4, gold = { herb = 7.5 }, ended = 99 },
        { elapsed = 7200, gold = { loot = 150 } },
      } }""",
    # Nothing at all.
    """GoldPerHourDB = {}""",
]

out = ["// Code generated by a Python script from Python's own output; DO NOT EDIT.", "", "package goldperhour", "",
       "var fromDBCases = []struct {", "\tlua  string", "\twant string", "}{"]
for lua in cases:
    with tempfile.NamedTemporaryFile("w", suffix=".lua", delete=False, encoding="utf-8") as f:
        f.write(lua)
    db = upgrades.load_sv(f.name, "GoldPerHourDB") or {}
    os.unlink(f.name)
    got = goldperhour.from_db(db)
    out.append("\t{%s, %s}," % (json.dumps(lua, ensure_ascii=False), json.dumps(json.dumps(got, ensure_ascii=False),
                                                                             ensure_ascii=False)))
out.append("}")
with open(os.path.join(HERE, "cases_test.go"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
