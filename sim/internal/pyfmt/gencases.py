"""Writes cases_test.go next to this file: Python's own output for every spec the texts use, on edge values.

    python3 sim/internal/pyfmt/gencases.py && gofmt -w sim/internal/pyfmt
"""
import json
import os

values = [0, 1, -1, 7, 42, 1234, -1234, 1234567, 0.0, -0.0, 0.5, 1.5, 2.5, 2.675, 0.125, 0.1, 1 / 3, 2 / 3,
          12.0, 99.95, 100.0, 1234.5, -1234.5, 0.000123, 1e-5, 0.0001, 1e16, 1234567890123456.0, 1e22, 123456.0,
          1e6, 0.015, 0.045, 10.25, 3.14159, -0.4, 59.999, 0.995, 1795289733.114016, 5e-324, 1.7976931348623157e308]
specs = ["", "g", ".1f", ".0%", ".0f", ".2f", ".4f", ".3f", "+.0f", "6.1f", "+.1f", "02d", ",.0f", ",", "+d", "3d",
         ">8", ">7,", "7.1f", ".2%", "e", ".1e", ".2g", "05.1f", "<6", "^7"]
rounds = [(2.5, 0), (3.5, 0), (2.675, 2), (0.125, 2), (0.375, 2), (1.005, 2), (-2.5, 0), (12.345, 1), (1234.5, -1),
          (0.1 + 0.2, 1), (59.95, 1), (1e16 + 1, 0)]
lines = ["// Code generated by a Python script from Python's own output; DO NOT EDIT.", "", "package pyfmt", "",
         "var specCases = []struct {", "\tv    any", "\tspec string", "\twant string", "}{"]
for v in values:
    for s in specs:
        if isinstance(v, float) and s.endswith("d"):
            continue
        try:
            got = format(v, s)
        except (ValueError, OverflowError):
            continue
        gv = repr(v) if isinstance(v, int) else ("float64(%r)" % v if repr(v) not in ("inf", "nan") else None)
        if gv is None:
            continue
        if isinstance(v, float):
            gv = "float64(" + json.dumps(v) + ")" if v == v else None
            if v == 0 and str(v).startswith("-"):
                gv = "negZero"
        lines.append("\t{%s, %s, %s}," % (gv, json.dumps(s), json.dumps(got, ensure_ascii=False)))
for v in ["Text", "Grün", None, True, False]:
    for s in ["", ">8", "<6", "^7"]:
        if v is None and s:
            continue
        try:
            got = format(v, s)
        except ValueError:
            continue
        gv = {None: "nil", True: "true", False: "false"}.get(v) if not isinstance(v, str) else json.dumps(v)
        lines.append("\t{%s, %s, %s}," % (gv, json.dumps(s), json.dumps(got, ensure_ascii=False)))
lines.append("}")
lines += ["", "var roundCases = []struct {", "\tx    float64", "\tn    int", "\twant float64", "}{"]
for x, n in rounds:
    lines.append("\t{%s, %d, %s}," % (json.dumps(x), n, json.dumps(float(round(x, n)))))
lines.append("}")
lines += ["", "var formatCases = []struct {", "\ttext string", "\tvals map[string]any", "\twant string", "}{"]
for text, vals in [("only {n} items in the AH", {"n": 3}), ("{a:.1f} and {b:g}", {"a": 2.25, "b": 0.5}),
                   ("{{literal}} {x}", {"x": "y"}), ("{share:.0%} of {pts:.1f}", {"share": 0.255, "pts": 12.345})]:
    go_vals = ", ".join(f"{json.dumps(k)}: {('float64(' + json.dumps(v) + ')') if isinstance(v, float) else json.dumps(v)}"
                        for k, v in vals.items())
    lines.append("\t{%s, map[string]any{%s}, %s}," % (json.dumps(text), go_vals, json.dumps(text.format(**vals))))
lines.append("}")

# sum(): floats only, and ints mixed in (CPython 3.12/3.13 add an int after a float without compensation).
import random  # noqa: E402
import sys  # noqa: E402

assert sys.version_info[:2] in ((3, 12), (3, 13)), "run with Python 3.12 or 3.13: sum() of 3.14 differs for ints"
random.seed(11)


def go_num(x):
    return "int64(%d)" % x if isinstance(x, int) else "float64(%s)" % json.dumps(x)


lines += ["", "var sumCases = []struct {", "\txs   []any", "\twant any", "}{"]
for n in range(300):
    xs = []
    for _ in range(random.randint(1, 10)):
        r = random.random()
        if r < 0.25 and n % 2:
            xs.append(random.randint(-500, 500))
        elif r < 0.6:
            xs.append(random.uniform(-1e3, 1e3))
        else:
            xs.append(random.choice([0.1, 0.2, 0.3, 1e16, -1e16, 1.0, 0.7, 2.675, 0.01, 0.6]) * random.choice([1, 3, 7]))
    lines.append("\t{[]any{%s}, %s}," % (", ".join(go_num(x) for x in xs), go_num(sum(xs))))
lines.append("}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "cases_test.go"), "w").write("\n".join(lines) + "\n")
print(len(lines), "lines")
